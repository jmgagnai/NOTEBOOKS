// Writes src/app/shared/fluent-icons.generated.ts from the Fluent UI System
// Icons package (NBK-31). The SVGs are copied into a TypeScript literal map
// rather than loaded as assets at runtime so the registry is filled
// synchronously at startup — no HTTP round trip per icon, no asset glob to
// keep in sync, and the bundle carries exactly the names below. Re-run with
// `pnpm --filter frontend icons:generate` after changing the list.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * The explicit set spec 01 "Icons" registers, plus spec 02's three, the title
 * bar's sign-out and spec 04's history (the Chat Threads navigator's title).
 */
const NAMES = [
  'add',
  'history',
  'search',
  'more-horizontal',
  'delete',
  'arrow-download',
  'open',
  'send',
  'rename',
  'chevron-down',
  'notebook',
  'document',
  'sparkle',
  'dismiss',
  'checkmark',
  'warning',
  'arrow-left',
  'panel-right-contract',
  'panel-right-expand',
  'sign-out',
];

const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve('@fluentui/svg-icons/package.json')), 'icons');
const { version } = require('@fluentui/svg-icons/package.json');

const entries = NAMES.map((name) => {
  const file = join(iconsDir, `${name.replaceAll('-', '_')}_20_regular.svg`);
  const svg = readFileSync(file, 'utf8').trim();
  if (!svg.startsWith('<svg')) throw new Error(`${file} does not look like an SVG`);
  return `  '${name}': ${JSON.stringify(svg)},`;
});

const out = `// GENERATED by apps/frontend/scripts/generate-fluent-icons.mjs — do not edit.
// Fluent UI System Icons © Microsoft, MIT (@fluentui/svg-icons ${version},
// regular style, 20 px). Licence: ./fluent-icons.LICENSE.md

export const FLUENT_ICONS = {
${entries.join('\n')}
} as const;
`;

const target = fileURLToPath(new URL('../src/app/shared/fluent-icons.generated.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${NAMES.length} icons to ${target}`);
